// localStorage mínimo para Node, importado ANTES que los módulos de la app
// para que config.js y store.js lo detecten al cargarse.
const mem = new Map();
globalThis.localStorage = {
  getItem: (k) => (mem.has(k) ? mem.get(k) : null),
  setItem: (k, v) => mem.set(k, String(v)),
  removeItem: (k) => mem.delete(k),
  clear: () => mem.clear(),
};
